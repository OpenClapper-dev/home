#!/usr/bin/env node
// Writes apps/site/wrangler.deploy.jsonc (gitignored) from the tracked local-dev config plus one
// deployment's settings. The tracked config names no Cloudflare account, database or Access app.
//
//   node scripts/deploy-config.mjs [--provision]
//
// Settings come from the environment only, never from a file (the Deploy workflow exports them from
// a GitHub environment, docs/deploying.md). An empty variable counts as unset.
//   CLOUDFLARE_ACCOUNT_ID   required
//   D1_DATABASE_ID          required, unless --provision finds or creates the database by name
//   D1_DATABASE_NAME        default openclapper-home
//   D1_LOCATION             optional location hint when --provision creates the database (weur, enam…)
//   WORKER_NAME             default openclapper-home
//   SITE_DOMAIN             the custom domain, e.g. openclapper.org (a zone in the same account); empty: workers.dev only
//   SITE_URL                default https://<SITE_DOMAIN>: where the confirmation link and Turnstile's hostname check point
//   MAIL_FROM               default "OpenClapper <noreply@<SITE_DOMAIN>>"; its domain must be onboarded to Email Service
//   ACCESS_TEAM_DOMAIN      your Zero Trust team domain (the admin view needs it)
//   ACCESS_AUD              the admin Access application's AUD; without it /admin refuses every request
//   TURNSTILE_SITEKEY       read by vite.config.ts at build time, not here
//   TURNSTILE_SECRET        a Worker secret, set by the workflow after the deploy
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const provision = process.argv.includes("--provision");
const env = Object.fromEntries(Object.entries(process.env).filter(([, v]) => v !== ""));
const setting = (k, fallback) => env[k] ?? fallback;
const fail = (msg) => { console.error(`deploy-config: ${msg}`); process.exit(1); };

/** JSON with // and /* comments (wrangler.jsonc); strings are kept as they are. */
function parseJsonc(text) {
  let out = "", i = 0;
  while (i < text.length) {
    const c = text[i];
    if (c === '"') { let j = i + 1; while (j < text.length && text[j] !== '"') j += text[j] === "\\" ? 2 : 1; out += text.slice(i, j + 1); i = j + 1; }
    else if (text.startsWith("//", i)) i = text.indexOf("\n", i) === -1 ? text.length : text.indexOf("\n", i);
    else if (text.startsWith("/*", i)) i = text.indexOf("*/", i) + 2;
    else { out += c; i++; }
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

const accountId = setting("CLOUDFLARE_ACCOUNT_ID") ?? fail("CLOUDFLARE_ACCOUNT_ID is not set");
const dbName = setting("D1_DATABASE_NAME", "openclapper-home");
const site = join(root, "apps/site");
const wrangler = (...args) => execFileSync("npx", ["wrangler", ...args], { cwd: site, env: { ...process.env, CLOUDFLARE_ACCOUNT_ID: accountId }, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] });

let dbId = setting("D1_DATABASE_ID");
if (provision && !dbId) {
  const found = JSON.parse(wrangler("d1", "list", "--json")).find((d) => d.name === dbName);
  if (found) dbId = found.uuid;
  else {
    console.log(`deploy-config: creating D1 database ${dbName}`);
    wrangler("d1", "create", dbName, ...(env.D1_LOCATION ? ["--location", env.D1_LOCATION] : []));
    dbId = JSON.parse(wrangler("d1", "list", "--json")).find((d) => d.name === dbName)?.uuid;
  }
}
if (!dbId) fail("D1_DATABASE_ID is not set (or run with --provision)");

const domain = setting("SITE_DOMAIN");
const base = parseJsonc(readFileSync(join(site, "wrangler.jsonc"), "utf8"));
delete base.$schema;
const config = {
  ...base,
  name: setting("WORKER_NAME", "openclapper-home"),
  account_id: accountId,
  // Workers assets serves this from dist/, as the tracked config does.
  vars: {
    ACCESS_TEAM_DOMAIN: setting("ACCESS_TEAM_DOMAIN", ""),
    ACCESS_AUD: setting("ACCESS_AUD", ""),
    SITE_URL: setting("SITE_URL", domain ? `https://${domain}` : ""),
    MAIL_FROM: setting("MAIL_FROM", domain ? `OpenClapper <noreply@${domain}>` : ""),
  },
  d1_databases: [{ binding: "DB", database_name: dbName, database_id: dbId, migrations_dir: "migrations" }],
  ...(domain ? { routes: [{ pattern: domain, custom_domain: true }] } : {}),
};
if (!config.vars.SITE_URL) fail("SITE_URL is not set (and no SITE_DOMAIN to derive it from)");
if (!config.vars.MAIL_FROM) fail("MAIL_FROM is not set (and no SITE_DOMAIN to derive it from)");

const out = join(site, "wrangler.deploy.jsonc");
writeFileSync(out, `// Generated by scripts/deploy-config.mjs from the environment; gitignored. Do not edit.\n${JSON.stringify(config, null, 2)}\n`);
console.log(`deploy-config: wrote ${out} (${config.name}, D1 ${dbName} ${dbId}${domain ? `, ${domain}` : ""})`);
